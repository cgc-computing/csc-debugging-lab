// quote_printer.cpp
// Prints a "Quote of the Day" banner, a two-line quotation from Grace Hopper,
// and the attribution.
#include <iostream>
using namespace std;

int main() {
    cout << "===============================" << endl;
    cout << "       Quote of the Day" << endl;
    cout << "===============================" << endl;
    cout << "The most dangerous phrase in the language is," << endl;
    cout << "'We've always done it this way.'" << endl;
    cout << "        -- Grace Hopper" << endl;
    cout << endl;
    cout << "Have a great lab session!" << endl;
    return 0;
}
