// QuotePrinter.java
// Prints a short four-line quotation, one line at a time, with a title above it.

public class QuotePrinter {
    public static void main(String[] args) {
        System.out.println("A Favorite Quotation");
        System.out.println("--------------------");
        System.out.println("Do not go where the path may lead;");
        System.out.println("go instead where there is no path");
        System.out.println("and leave a trail.");
        System.out.println("      -- Ralph Waldo Emerson");
    }
}
